"""Генератор конечных ролей и навыков агентов из матрицы `HYAI/core/agents`.

Источник: `roles.yaml` (архетип × зона × тип работы), архетипы, зоны, политики и
архетипонезависимые навыки. Проекции пишутся в `.claude` и `.opencode`.

Выбор формата: в проекции включается полный текст источников плюс ссылка на
источник. Оболочка агента не обязана разрешать относительные ссылки во время
работы, а расхождение исправляется одной пересборкой. Авторские файлы не трогаются:
у состоящих под управлением генератора файлов есть MARKER.

Проверка дрейфа: `python3 HYAI/tools/build_agents.py --check`.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _shared as sh

MARKER = "<!-- generated by HYAI/tools/build_agents.py; правки вносятся в источники -->"
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
FRONT_RE = re.compile(r"\A---\s*\n.*?\n---\s*\n", re.DOTALL)
AGENT_PREFIX = "hyai-"
SKILL_PREFIX = "hyai-agent-"
ROUTER_NAME = "hyai-agents"
OUT_ROOTS = (".claude", ".opencode")
MAX_DESCRIPTION = 1024


class BuildError(Exception):
    """Нет данных для сборки: код возврата 2, а не частичный результат."""


def source_dir(root: Path) -> Path:
    return sh.core_dir(root) / "core" / "agents"


def need_text(path: Path, what: str) -> str:
    if not path.is_file():
        raise BuildError(f"нет {what}: {sh.rel_posix(Path.cwd(), path)}")
    return path.read_text(encoding="utf-8").strip()


def strip_front(text: str) -> str:
    return FRONT_RE.sub("", text).strip()


def read_data(src: Path) -> dict:
    path = src / "roles.yaml"
    if not path.is_file():
        raise BuildError("нет матрицы: HYAI/core/agents/roles.yaml")
    data = sh.load_yaml(path)
    for key in ("archetypes", "zones", "work_types", "roles"):
        if key not in data:
            raise BuildError(f"в roles.yaml нет раздела {key}")
    for key in ("archetypes", "zones", "work_types"):
        if not isinstance(data[key], dict) or not data[key]:
            raise BuildError(f"раздел {key} пуст или не словарь")
    if not isinstance(data["roles"], list) or not data["roles"]:
        raise BuildError("раздел roles пуст или не список")
    seen: set[str] = set()
    for role in data["roles"]:
        for key in ("id", "name", "archetype", "zone", "work", "summary"):
            if not role.get(key):
                raise BuildError(f"роль без поля {key}: {role.get('id', '?')}")
        ident = str(role["id"])
        if not NAME_RE.fullmatch(ident) or ident in seen:
            raise BuildError(f"некорректный или повторный id роли: {ident!r}")
        seen.add(ident)
        for key, section in (("archetype", "archetypes"), ("zone", "zones"), ("work", "work_types")):
            if str(role[key]) not in data[section]:
                raise BuildError(f"роль {ident}: нет {key} {role[key]!r} в {section}")
    return data


def rel_link(target: Path, from_dir: Path) -> str:
    return Path(os.path.relpath(target, from_dir)).as_posix()


def policy_paths(src: Path, archetype: str, zone: str) -> list[Path]:
    """Сначала специфичные политики, затем общие."""
    found: list[Path] = []
    for directory in (src / "archetypes" / f"{archetype}-policies",
                      src / "domains" / f"{zone}-policies",
                      src / "policies"):
        if directory.is_dir():
            found.extend(sorted(path for path in directory.glob("*.md")
                                if path.name != "README.md"))
    return found


def skill_sources(src: Path, archetype: str, work: str) -> tuple[Path, Path | None]:
    generic = src / "skills" / work / "SKILL.md"
    need_text(generic, f"общий навык {work}")
    specific = src / "archetypes" / f"{archetype}-skills" / work / "SKILL.md"
    return generic, specific if specific.is_file() else None


def skill_text(name: str, description: str, body: str) -> str:
    if not NAME_RE.fullmatch(name) or len(name) > 64:
        raise BuildError(f"имя навыка не по стандарту: {name!r}")
    if not description or len(description) > MAX_DESCRIPTION:
        raise BuildError(f"навык {name!r}: описание пусто или длиннее {MAX_DESCRIPTION}")
    header = ("---\n"
              f"name: {name}\n"
              f"description: {json.dumps(description, ensure_ascii=False)}\n"
              "---\n")
    return f"{header}\n{MARKER}\n\n{body.strip()}\n"


def agent_text(role: dict, data: dict, src: Path, agent_file: Path, root: Path) -> str:
    ident = str(role["id"])
    archetype = str(role["archetype"])
    zone = str(role["zone"])
    work = str(role["work"])
    a_data = data["archetypes"][archetype]
    z_data = data["zones"][zone]
    w_data = data["work_types"][work]

    a_doc = src / "archetypes" / f"{archetype}.md"
    z_doc = src / str(z_data["behavior"])
    generic, specific = skill_sources(src, archetype, work)

    relations = src / "RELATIONS.md"
    sources = [relations, a_doc, z_doc, generic]
    if specific:
        sources.append(specific)
    policies = policy_paths(src, archetype, zone)
    sources.extend(policies)

    texts = {path: need_text(path, "источник") for path in sources}
    lines = [
        f"Обязательно ознакомься с глобальным [`/HYAI/AGENTS.md`]({rel_link(root / 'AGENTS.md', agent_file.parent)}).",
        "",
        MARKER,
        "",
        f"# {role['name']}",
        "",
        "Goal",
        "```",
        str(role["summary"]),
        "```",
        "",
        "Backstory",
        "```",
        (f"Ты — {role['name']}. Архетип: {a_data.get('name', archetype)}. "
         f"Зона: {z_data.get('name', zone)}. Тип работы: {w_data.get('name', work)}."),
        "",
        strip_front(texts[a_doc]),
        "",
        strip_front(texts[z_doc]),
        "",
        strip_front(texts[generic]),
    ]
    if specific:
        lines += ["", strip_front(texts[specific])]
    lines += [
        "",
        "```",
        "",
        "Taste & Judgments",
        "```",
        "- Обязательно прочитай RELATIONS.md: граф связей и ворота готовности.",
        "- Сначала специфичные политики и навыки архетипа и зоны, затем общие.",
        "- Не объявляй готовность уровень выше без аудита своего уровня.",
        "- Не вступай в прямую связь с другими отделами: запрос через своего КУО.",
    ]
    if zone == "self":
        lines += [
            "- Разжёвывай задачу до конкретных шагов: вход, действие, результат, критерий.",
            "- Не оставляй неявных допущений: указывай пути, имена и форматы.",
            "- Чем проще исполнитель, тем мельче шаги; проверяй шаг сразу.",
        ]
    lines += [
        "```",
        "",
        "## Политики",
        "",
    ]
    if policies:
        for path in policies:
            lines += [f"### {path.stem}", "", texts[path], ""]
    else:
        lines += ["—", ""]
    lines += [
        "## Граф связей — обязательное чтение",
        "",
        "Используй только рёбра этого графа и соблюдай ворота готовности.",
        "",
        strip_front(texts[relations]),
        "",
    ]
    lines += ["## Источники", ""]
    for path in sources:
        lines.append(f"- [`{sh.rel_posix(src, path)}`]({rel_link(path, agent_file.parent)})")
    return "\n".join(lines).rstrip() + "\n"


def role_skill_text(archetype: str, work: str, data: dict, src: Path, skill_file: Path) -> str:
    a_data = data["archetypes"][archetype]
    w_data = data["work_types"][work]
    generic, specific = skill_sources(src, archetype, work)
    sources = [generic] + ([specific] if specific else [])
    texts = {path: need_text(path, "навык") for path in sources}
    name = f"{SKILL_PREFIX}{archetype}-{work}"
    description = (f"{a_data.get('name', archetype)}: {w_data.get('name', work)}. "
                   f"{w_data.get('description', '')} Общий регламент + уточнение архетипа.")
    lines = [
        f"# {a_data.get('name', archetype)} — {w_data.get('name', work)}",
        "",
        "Навык объединяет архетипонезависимый регламент и уточнение архетипа.",
        "",
        "## Общий регламент",
        "",
        strip_front(texts[generic]),
    ]
    if specific:
        lines += ["", "## Уточнение архетипа", "", strip_front(texts[specific])]
    lines += ["", "## Источники", ""]
    for path in sources:
        lines.append(f"- [`{sh.rel_posix(src, path)}`]({rel_link(path, skill_file.parent)})")
    return skill_text(name, description, "\n".join(lines))


def router_text(data: dict, skill_dir: Path, out_root: Path, src: Path) -> str:
    rows = ["| Роль | Архетип | Зона | Тип работы | Агент |", "| --- | --- | --- | --- | --- |"]
    for role in data["roles"]:
        agent = out_root / "agents" / f"{AGENT_PREFIX}{role['id']}.md"
        rows.append(
            f"| {role['name']} | `{role['archetype']}` | `{role['zone']}` | `{role['work']}` "
            f"| [`{agent.name}`]({rel_link(agent, skill_dir)}) |")
    description = ("Матрица ролей агентов: архетип × зона ответственности × тип работы. "
                   "Используй, чтобы выбрать агента и понять границы его зоны.")
    body = "\n".join([
        "# Агенты HYAI по матрице ролей",
        "",
        "Конкретная роль получается пересечением архетипа, зоны и типа работы.",
        "Тип работы переключается в процессе без смены архетипа и зоны.",
        "",
        "\n".join(rows),
        "",
        f"Обязательное чтение: [`RELATIONS.md`]({rel_link(src / 'RELATIONS.md', skill_dir)}).",
        "Общие правила чтения: специфичные политики и навыки раньше общих.",
    ])
    return skill_text(ROUTER_NAME, description, body)


def build(root: Path) -> dict[str, str]:
    src = source_dir(root)
    data = read_data(src)
    files: dict[str, str] = {}
    for out_name in OUT_ROOTS:
        out_root = root / out_name
        for role in data["roles"]:
            rel = f"{out_name}/agents/{AGENT_PREFIX}{role['id']}.md"
            files[rel] = agent_text(role, data, src, root / rel, root)
        pairs = sorted({(str(r["archetype"]), str(r["work"])) for r in data["roles"]})
        for archetype, work in pairs:
            rel = f"{out_name}/skills/{SKILL_PREFIX}{archetype}-{work}/SKILL.md"
            files[rel] = role_skill_text(archetype, work, data, src, root / rel)
        files[f"{out_name}/skills/{ROUTER_NAME}/SKILL.md"] = router_text(
            data, out_root / "skills" / ROUTER_NAME, out_root, src)
    return files


def stale_paths(root: Path, files: dict[str, str]) -> list[Path]:
    """Только файлы с нашим MARKER: авторские и проекции других генераторов не трогаем."""
    expected = {str(root / rel) for rel in files}
    found: list[Path] = []
    for out_name in OUT_ROOTS:
        agents = root / out_name / "agents"
        if agents.is_dir():
            for path in agents.glob(f"{AGENT_PREFIX}*.md"):
                if str(path) not in expected and MARKER in path.read_text(encoding="utf-8"):
                    found.append(path)
        skills = root / out_name / "skills"
        if skills.is_dir():
            for directory in skills.iterdir():
                skill = directory / "SKILL.md"
                if (directory.is_dir() and skill.is_file()
                        and str(skill) not in expected
                        and MARKER in skill.read_text(encoding="utf-8")):
                    found.append(directory)
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description="Генератор агентов и навыков по матрице ролей")
    parser.add_argument("--root", default=str(sh.DEFAULT_ROOT))
    parser.add_argument("--check", action="store_true", help="проверить дрейф (по умолчанию)")
    parser.add_argument("--write", action="store_true", help="записать проекции")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    try:
        files = build(root)
    except BuildError as error:
        print(str(error), file=sys.stderr)
        return 2

    stale = stale_paths(root, files)
    if args.write:
        for path in stale:
            if path.is_dir():
                shutil.rmtree(path)
            else:
                path.unlink()
        for rel, text in files.items():
            target = root / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        if not args.json:
            agents = sum(1 for rel in files if "/agents/" in rel)
            skills = sum(1 for rel in files if "/skills/" in rel)
            print(f"агентов: {agents}; навыков: {skills}; удалено устаревших: {len(stale)}")
        return 0

    drift: list[str] = []
    for rel, text in files.items():
        target = root / rel
        if not target.exists():
            drift.append(f"{rel}: не собран")
        elif target.read_text(encoding="utf-8") != text:
            drift.append(f"{rel}: дрейф")
    for path in stale:
        drift.append(f"{sh.rel_posix(root, path)}: лишний сгенерированный файл")
    if args.json:
        print(json.dumps({"drift": drift, "files": len(files)}, ensure_ascii=False))
        return 1 if drift else 0
    if drift:
        for line in drift[:60]:
            print(f"  {line}")
        print(f"\nдрейф: {len(drift)}; запустите build_agents.py --write")
        return 1
    print(f"актуально: {len(files)} файлов; устаревших: {len(stale)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
