"""Сборка навыков Agent Skills: формат, актуальность, устаревшие и триггеры."""

from __future__ import annotations

import re
import sys
import unittest
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _kit import KitCopy  # noqa: E402

NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
LINK_RE = re.compile(r"(?<!!)\[[^\]]*\]\(([^)\s]+)\)")
OUT = ".claude/skills"
MARKER = "<!-- generated by HYAI/tools/build_skills.py; правки вносятся в источники -->"


def skill_dirs(kit: KitCopy) -> list[Path]:
    root = kit.path(OUT)
    return sorted(path for path in root.iterdir() if path.is_dir()) if root.exists() else []


def frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    return yaml.safe_load(text[3:end]) or {}


def workflow_with_trigger(kit: KitCopy) -> Path:
    """Первый процесс первого активного домена: тест не знает имён доменов."""
    man = kit.load("HYAI/meta/manifest.yaml")
    domain = str((man.get("active") or [{}])[0].get("domain") or "")
    data = kit.load(str((man.get("domains") or {})[domain]))
    directory = kit.path(str(data["workflows_dir"]))
    return next(path for path in sorted(directory.glob("*.md")) if path.name != "README.md")


class SkillsBuildTest(unittest.TestCase):
    def setUp(self) -> None:
        self.kit = KitCopy()

    def tearDown(self) -> None:
        self.kit.close()

    def test_generated_catalog_is_actual(self) -> None:
        res = self.kit.run("build_skills.py", "--check")
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)

    def test_drift_after_source_change_is_detected(self) -> None:
        man = self.kit.load("HYAI/meta/manifest.yaml")
        domain = str((man.get("active") or [{}])[0].get("domain") or "")
        data = self.kit.load(str((man.get("domains") or {})[domain]))
        profile_rel = str(next(iter((data.get("profiles") or {}).values())))
        text = self.kit.read(profile_rel)
        self.kit.write(profile_rel, text.replace("topic: ", "topic: Изменено. ", 1))
        res = self.kit.run("build_skills.py", "--check")
        self.assertEqual(res.returncode, 1, res.stdout)

    def test_missing_config_is_an_error(self) -> None:
        man = self.kit.load("HYAI/meta/manifest.yaml")
        man.pop("skills", None)
        self.kit.dump("HYAI/meta/manifest.yaml", man)
        res = self.kit.run("build_skills.py", "--check")
        self.assertEqual(res.returncode, 2)
        self.assertIn("skills", res.stderr)

    def test_names_and_descriptions_follow_the_standard(self) -> None:
        for directory in skill_dirs(self.kit):
            meta = frontmatter(directory / "SKILL.md")
            self.assertEqual(meta.get("name"), directory.name)
            self.assertRegex(str(meta.get("name")), NAME_RE)
            self.assertLessEqual(len(str(meta.get("name"))), 64)
            self.assertLessEqual(len(str(meta.get("description") or "")), 1024)
            self.assertTrue(meta.get("description"))

    def test_generated_links_resolve(self) -> None:
        checked = 0
        for skill in skill_dirs(self.kit):
            for page in sorted(skill.rglob("*.md")):
                for target in LINK_RE.findall(page.read_text(encoding="utf-8")):
                    if target.startswith(("http", "#", "mailto:")):
                        continue
                    checked += 1
                    resolved = (page.parent / target.split("#", 1)[0]).resolve()
                    self.assertTrue(resolved.exists(), f"{page}: {target}")
        self.assertGreater(checked, 0)

    def test_skills_hold_no_external_links(self) -> None:
        for directory in skill_dirs(self.kit):
            for page in sorted(directory.rglob("*.md")):
                text = page.read_text(encoding="utf-8")
                self.assertNotIn("http://", text, f"{page}: ссылка устареет молча")
                self.assertNotIn("https://", text, f"{page}: ссылка устареет молча")

    def test_skill_files_are_not_hyai_documents(self) -> None:
        self.assertTrue(any(skill_dirs(self.kit)))
        res = self.kit.run("frontmatter.py", "--check")
        self.assertEqual(res.returncode, 0, res.stdout)


class SkillsStalenessTest(unittest.TestCase):
    def setUp(self) -> None:
        self.kit = KitCopy()

    def tearDown(self) -> None:
        self.kit.close()

    def test_stale_generated_skill_is_reported_and_removed(self) -> None:
        stale = self.kit.path(f"{OUT}/hyai-obsolete")
        stale.mkdir(parents=True, exist_ok=True)
        (stale / "SKILL.md").write_text(
            f"---\nname: hyai-obsolete\ndescription: \"устаревший\"\n---\n\n{MARKER}\n",
            encoding="utf-8")
        res = self.kit.run("build_skills.py", "--check")
        self.assertEqual(res.returncode, 1)
        self.assertIn("устаревший", res.stdout)

        written = self.kit.run("build_skills.py", "--write")
        self.assertEqual(written.returncode, 0, written.stdout)
        self.assertFalse(stale.exists())

    def test_manual_skill_without_marker_is_kept(self) -> None:
        manual = self.kit.path(f"{OUT}/team-skill")
        manual.mkdir(parents=True, exist_ok=True)
        (manual / "SKILL.md").write_text("---\nname: team-skill\ndescription: \"своё\"\n---\n",
                                        encoding="utf-8")
        self.kit.run("build_skills.py", "--write")
        self.assertTrue(manual.exists())


class SkillsTriggerTest(unittest.TestCase):
    def setUp(self) -> None:
        self.kit = KitCopy()

    def tearDown(self) -> None:
        self.kit.close()

    def test_workflow_without_trigger_produces_no_skill(self) -> None:
        workflow = workflow_with_trigger(self.kit)
        stem = workflow.stem
        self.assertFalse(any(directory.name.endswith(stem) for directory in skill_dirs(self.kit)))

    def test_workflow_with_trigger_produces_skill(self) -> None:
        workflow = workflow_with_trigger(self.kit)
        rel = str(workflow.relative_to(self.kit.root)).replace("\\", "/")
        text = self.kit.read(rel)
        end = text.find("\n---", 3)
        self.assertNotEqual(end, -1)
        self.kit.write(rel, text[:end] + '\nwhen_to_use: "Проверка триггера в тесте"' + text[end:])

        res = self.kit.run("build_skills.py", "--write")
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        names = [directory.name for directory in skill_dirs(self.kit)]
        self.assertTrue(any(name.endswith(workflow.stem) for name in names), names)

        domain_prefix = next(name for name in names if not name.endswith(workflow.stem))
        meta = frontmatter(self.kit.path(f"{OUT}/{domain_prefix}/SKILL.md"))
        self.assertTrue(meta.get("name"))


class AuthoredSkillsTest(unittest.TestCase):
    """Авторские навыки внешних инструментов: копия, границы переносимости, ошибки источника."""

    KIT_MARKERS = ("metamcp", "mcp-kit", "13001", "12008", "12208", "192.168",
                   "X-API-Key", "Mcp-Session-Id")

    def setUp(self) -> None:
        self.kit = KitCopy()
        man = self.kit.load("HYAI/meta/manifest.yaml")
        self.source_rel = str(man["skills"]["authored"])

    def tearDown(self) -> None:
        self.kit.close()

    def sources(self) -> list[str]:
        directory = self.kit.path(self.source_rel)
        return sorted(path.parent.name for path in directory.glob("*/SKILL.md"))

    def test_every_source_is_in_the_catalog(self) -> None:
        present = {directory.name for directory in skill_dirs(self.kit)}
        sources = self.sources()
        self.assertGreater(len(sources), 30, sources)
        for name in sources:
            self.assertIn(name, present)

    def test_catalog_is_a_copy_of_the_source(self) -> None:
        for name in self.sources():
            source = self.kit.read(f"{self.source_rel}{name}/SKILL.md")
            source_body = source.split("\n---", 1)[1]
            catalog = self.kit.read(f"{OUT}/{name}/SKILL.md")
            self.assertIn(source_body.strip()[:200], catalog)

    def test_skills_hold_no_installation_specifics(self) -> None:
        for name in self.sources():
            text = self.kit.read(f"{OUT}/{name}/SKILL.md").lower()
            for marker in self.KIT_MARKERS:
                self.assertNotIn(marker.lower(), text, f"{name}: {marker}")

    def test_name_must_match_its_directory(self) -> None:
        first = self.sources()[0]
        rel = f"{self.source_rel}{first}/SKILL.md"
        self.kit.write(rel, self.kit.read(rel).replace(f"name: {first}", "name: other-name", 1))
        res = self.kit.run("build_skills.py", "--check")
        self.assertEqual(res.returncode, 2)
        self.assertIn("не совпадает", res.stderr)

    def test_source_without_description_is_rejected(self) -> None:
        first = self.sources()[0]
        rel = f"{self.source_rel}{first}/SKILL.md"
        text = self.kit.read(rel)
        stripped = "\n".join(line for line in text.splitlines()
                             if not line.startswith("description:"))
        self.kit.write(rel, stripped)
        res = self.kit.run("build_skills.py", "--check")
        self.assertEqual(res.returncode, 2)


if __name__ == "__main__":
    unittest.main()
