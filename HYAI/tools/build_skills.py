"""Сборка навыков Agent Skills из активных доменов и профилей HYAI.

Навык — проекция, а не источник правила: право живёт в `AGENTS.md` и в политике домена,
поэтому удаление каталога навыков ничего не разрешает и не запрещает. Сборка идёт от данных:
активные домены (`active`), их профили (`profiles/*/profile.yaml`), заголовки разделов
политики, реестр «читать первым» и триггеры `when_to_use` в frontmatter процессов.

Имён доменов в коде нет (`3D`); нет данных — код возврата `2`, а не тихий пропуск.
`--check` сравнивает каталог с результатом сборки и возвращает `rc=1` при дрейфе.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import _shared as sh

MARKER = "<!-- generated by HYAI/tools/build_skills.py; правки вносятся в источники -->"
NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
HEADING_RE = re.compile(r"^##\s+(.+?)\s*$", re.MULTILINE)
RULE_BULLET_RE = re.compile(r"^-\s+`([A-Z][A-Z0-9-]*-\d{2,3})`\s+(.*)$")
RULE_PLAIN_RE = re.compile(r"^`([A-Z][A-Z0-9-]*-\d{2,3})`\.\s+(.*)$")
BOLD_RE = re.compile(r"\*\*(.+?)\*\*")
LINK_RE = re.compile(r"\[([^\]]*)\]\([^)]*\)")
PLACEHOLDER_RE = re.compile(r"\{\{[^}]+\}\}")
SLUG_RE = re.compile(r"[^a-z0-9]+")
PERM_ID_RE = re.compile(r"[A-Z][A-Z0-9-]*-N\d{2,3}")
MAX_DESCRIPTION = 1024
MAX_BODY_LINES = 500
CONFIG_KEYS = ("out", "templates", "router", "domain_prefix")


class BuildError(Exception):
    """Нет данных для сборки: код возврата 2, а не частичный результат."""


class Source:
    """Источники сборки: корень, манифест и вычисленные пути."""

    def __init__(self, root: Path) -> None:
        self.root = root
        man = sh.manifest(root)
        if not man:
            raise BuildError("HYAI/meta/manifest.yaml не найден")
        self.man = man
        self.cfg = man.get("skills") or {}
        missing = [key for key in CONFIG_KEYS if not self.cfg.get(key)]
        if missing:
            raise BuildError(f"в манифесте нет skills.{', skills.'.join(missing)}")
        self.templates = self.cfg.get("templates") or {}
        absent = [kind for kind in ("router", "domain", "procedure") if not self.templates.get(kind)]
        if absent:
            raise BuildError(f"в манифесте нет skills.templates.{', skills.templates.'.join(absent)}")
        self.out_dir = (root / str(self.cfg["out"])).resolve()
        self.prefix = str(self.cfg["domain_prefix"])
        self.entrypoint = str(man.get("entrypoint") or "AGENTS.md")
        self.domains = sh.domain_configs(root, man)

    def template(self, kind: str) -> str:
        rel = str(self.templates[kind])
        path = sh.fw(self.root, rel)
        if not path.exists():
            raise BuildError(f"шаблон навыка не найден: {rel}")
        _meta, body = sh.split_frontmatter(path.read_text(encoding="utf-8"))
        if not body.strip():
            raise BuildError(f"шаблон навыка пуст: {rel}")
        return body.strip()

    def active_domains(self) -> list[str]:
        active: list[str] = []
        for domain, _profile in sh.active_pairs(self.man):
            if domain not in active:
                active.append(domain)
        return active

    def domain_data(self, domain: str) -> dict:
        entry = self.domains.get(domain) or {}
        if not entry:
            raise BuildError(f"домен {domain!r} объявлен в active, но не найден в domains")
        data = entry.get("data") or {}
        if not data.get("policy"):
            raise BuildError(f"домен {domain!r}: в манифесте нет policy")
        return data


def render(template: str, values: dict[str, str]) -> str:
    text = template
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    left = sorted(set(PLACEHOLDER_RE.findall(text)))
    if left:
        raise BuildError(f"шаблон оставил плейсхолдеры: {', '.join(left)}")
    return text


def plain(text: str) -> str:
    text = LINK_RE.sub(r"\1", text)
    text = BOLD_RE.sub(r"\1", text).replace("`", "")
    return re.sub(r"\s+", " ", text).strip()


def cell(text: str, limit: int = 170, sentence: bool = True) -> str:
    text = plain(text)
    parenthetical = re.match(r"^\((.+?)\)[.:]\s*(.+)$", text)
    if parenthetical:
        text = parenthetical.group(2)
    if sentence:
        boundary = re.search(r"\.\s+(?=[А-ЯЁA-Z«\"])", text)
        if boundary and boundary.start() < limit:
            text = text[: boundary.start() + 1]
    if len(text) > limit:
        text = text[:limit].rsplit(" ", 1)[0].rstrip(" ,;:—") + "…"
    return text.replace("|", "\\|")


def rule_class(ident: str) -> str:
    return re.sub(r"-\d{2,3}$", "", ident)


def policy_classes(rules: list[tuple[str, str]]) -> str:
    counts: dict[str, int] = {}
    for ident, _text in rules:
        klass = rule_class(ident)
        counts[klass] = counts.get(klass, 0) + 1
    if not counts:
        return "—"
    rows = ["| Класс | Правил |", "| --- | --- |"]
    rows += [f"| `{klass}` | {count} |" for klass, count in counts.items()]
    return "\n".join(rows)


def rel_link(skill_dir: Path, target: Path) -> str:
    return Path(os.path.relpath(target, skill_dir)).as_posix()


def split_row(line: str) -> list[str]:
    parts = re.split(r"(?<!\\)\|", line.strip())
    return [part.strip() for part in parts[1:-1]]


def skill_text(name: str, description: str, body: str) -> str:
    if not NAME_RE.match(name) or len(name) > 64:
        raise BuildError(f"имя навыка {name!r} не по стандарту: [a-z0-9-], до 64 символов")
    if not description or len(description) > MAX_DESCRIPTION:
        raise BuildError(f"навык {name!r}: описание пусто или длиннее {MAX_DESCRIPTION} символов")
    header = ("---\n" f"name: {name}\n"
              f"description: {json.dumps(description, ensure_ascii=False)}\n---\n")
    return f"{header}\n{MARKER}\n\n{body.strip()}\n"


def policy_facts(source: Source, rel: str) -> tuple[list[str], list[tuple[str, str]]]:
    path = sh.fw(source.root, rel)
    if not path.exists():
        raise BuildError(f"политика домена не найдена: {rel}")
    _meta, body = sh.split_frontmatter(path.read_text(encoding="utf-8"))
    sections = [match.group(1) for match in HEADING_RE.finditer(body)]
    rules: list[tuple[str, str]] = []
    for line in body.splitlines():
        match = RULE_BULLET_RE.match(line) or RULE_PLAIN_RE.match(line)
        if match:
            rules.append((match.group(1), cell(match.group(2))))
    return sections, rules


def perm_rules(source: Source) -> list[tuple[str, str]]:
    rel = str((source.man.get("paths") or {}).get("kernel") or "") + "policies/permissions.md"
    path = sh.fw(source.root, rel)
    if not path.exists():
        raise BuildError(f"политика ядра не найдена: {rel}")
    rows: list[tuple[str, str]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = split_row(line)
        if len(cells) < 2:
            continue
        ident = cells[0].strip("`")
        if PERM_ID_RE.fullmatch(ident):
            rows.append((ident, cell(cells[1], 320, sentence=False)))
    if not rows:
        raise BuildError(f"в {rel} не найдено строк неотменяемых запретов")
    return rows


def profiles_table(source: Source, profiles: dict[str, str]) -> str:
    rows = ["| Профиль | Тема | Артефакты |", "| --- | --- | --- |"]
    for pname in sorted(profiles):
        data = sh.load_yaml(sh.fw(source.root, str(profiles[pname]))) or {}
        topic = cell(str(data.get("topic") or ""), 150) or "—"
        artifacts = ", ".join(str(item) for item in (data.get("produced_artifacts") or [])) or "—"
        rows.append(f"| `{pname}` | {topic} | {artifacts} |")
    return "\n".join(rows)


def read_first_block(source: Source, skill_dir: Path, registry_rel: str | None) -> str:
    if not registry_rel:
        return "—"
    registry = sh.load_yaml(sh.fw(source.root, str(registry_rel))) or {}
    lines = [f"- [`{rel}`]({rel_link(skill_dir, sh.fw(source.root, str(rel)))})"
             for rel in registry.get("read_first") or []]
    return "\n".join(lines) if lines else "—"


def bullets(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items) if items else "—"


def description_of(data: dict, domain: str) -> str:
    title = str((data.get("metadata") or {}).get("title") or domain)
    names = ", ".join(sorted(data.get("profiles") or {}))
    when = str((data.get("skills") or {}).get("when_to_use") or "").strip()
    tail = f"Когда применять: {when}" if when else (
        f"Используй, когда задача относится к домену {domain} каркаса HYAI.")
    return f"{title}. Профили: {names}. {tail}"


def domain_files(source: Source, domain: str) -> dict[str, str]:
    data = source.domain_data(domain)
    name = f"{source.prefix}{domain}"
    skill_dir = source.out_dir / name
    policy_rel = str(data["policy"])
    sections, rules = policy_facts(source, policy_rel)
    if not rules:
        raise BuildError(f"домен {domain!r}: в политике не найдено идентификаторов правил")
    title = str((data.get("metadata") or {}).get("title") or domain)
    access_rel = str((data.get("access") or {}).get("doc") or "") or policy_rel
    values = {
        "domain": domain,
        "title": title,
        "when_to_use": str((data.get("skills") or {}).get("when_to_use") or "").strip()
        or f"Задача относится к домену `{domain}`: {plain(title).lower()}.",
        "policy_classes": policy_classes(rules),
        "policy_sections": bullets([cell(item, 120, sentence=False) for item in sections]),
        "rule_count": str(len(rules)),
        "policy_link": rel_link(skill_dir, sh.fw(source.root, policy_rel)),
        "rules_index_link": "references/rules.md",
        "profiles_table": profiles_table(source, data.get("profiles") or {}),
        "checks": bullets([f"`{command}`" for command in data.get("checks") or []]),
        "read_first": read_first_block(source, skill_dir, data.get("registry")),
        "access_link": rel_link(skill_dir, sh.fw(source.root, access_rel)),
        "entrypoint": source.entrypoint,
    }
    body = render(source.template("domain"), values)
    files = {f"{name}/SKILL.md": skill_text(name, description_of(data, domain), body)}
    index_dir = skill_dir / "references"
    index = ["# Индекс правил домена", "",
             f"Полный текст — [`policy.md`]({rel_link(index_dir, sh.fw(source.root, policy_rel))}).",
             "", "| Правило | Начало |", "| --- | --- |"]
    index += [f"| `{ident}` | {text} |" for ident, text in rules]
    files[f"{name}/references/rules.md"] = "\n".join(index) + "\n"
    return files


def procedure_files(source: Source, domain: str) -> dict[str, str]:
    data = source.domain_data(domain)
    workflows_rel = str(data.get("workflows_dir") or "")
    if not workflows_rel:
        return {}
    directory = sh.fw(source.root, workflows_rel)
    if not directory.exists():
        return {}
    files: dict[str, str] = {}
    for path in sorted(directory.glob("*.md")):
        if path.name == "README.md":
            continue
        meta, _body = sh.split_frontmatter(path.read_text(encoding="utf-8"))
        when = str(meta.get("when_to_use") or "").strip()
        if not when:
            continue
        stem = SLUG_RE.sub("-", path.stem.lower()).strip("-")
        name = f"{source.prefix}{domain}-{stem}"
        skill_dir = source.out_dir / name
        domain_skill = f"{source.prefix}{domain}"
        title = str(meta.get("title") or path.stem)
        values = {
            "title": title,
            "when_to_use": when,
            "workflow_name": path.stem,
            "workflow_link": rel_link(skill_dir, path),
            "policy_link": rel_link(skill_dir, sh.fw(source.root, str(data["policy"]))),
            "domain": domain,
            "domain_skill": domain_skill,
            "domain_skill_link": rel_link(skill_dir, source.out_dir / domain_skill / "SKILL.md"),
            "checks": bullets([f"`{command}`" for command in data.get("checks") or []]),
            "entrypoint": source.entrypoint,
        }
        files[f"{name}/SKILL.md"] = skill_text(
            name, f"{title}. Когда применять: {when}", render(source.template("procedure"), values))
    return files


def router_files(source: Source, domains: list[str]) -> dict[str, str]:
    router_cfg = source.cfg.get("router") or {}
    name = str(router_cfg.get("name") or "hyai")
    description = str(router_cfg.get("description") or "").strip()
    if not description:
        raise BuildError("в манифесте нет skills.router.description")
    router_dir = source.out_dir / name
    rows = ["| Домен | Навык | Профили |", "| --- | --- | --- |"]
    for domain in domains:
        data = source.domain_data(domain)
        skill = f"{source.prefix}{domain}"
        rows.append(f"| `{domain}` | [`{skill}`]({rel_link(router_dir, source.out_dir / skill / 'SKILL.md')}) "
                    f"| {', '.join(sorted(data.get('profiles') or {}))} |")
    perm = ["| Правило | Запрет |", "| --- | --- |"]
    perm += [f"| `{ident}` | {text} |" for ident, text in perm_rules(source)]
    values = {"entrypoint": source.entrypoint, "domains_table": "\n".join(rows),
              "meta_dir": str((source.man.get("paths") or {}).get("meta") or "meta/"),
              "perm_rules": "\n".join(perm)}
    return {f"{name}/SKILL.md": skill_text(
        name, description, render(source.template("router"), values))}


def authored_files(source: Source) -> dict[str, str]:
    """Копия авторских навыков: `<dir>/<name>/SKILL.md` → `.github/skills/<name>/SKILL.md`."""
    rel = str(source.cfg.get("authored") or "")
    if not rel:
        return {}
    directory = sh.fw(source.root, rel)
    if not directory.exists():
        raise BuildError(f"каталог авторских навыков не найден: {rel}")
    files: dict[str, str] = {}
    for path in sorted(directory.glob("*/SKILL.md")):
        meta, body = sh.split_frontmatter(path.read_text(encoding="utf-8"))
        name = str(meta.get("name") or "")
        if not name:
            raise BuildError(f"{sh.rel_posix(source.root, path)}: нет поля name")
        if name != path.parent.name:
            raise BuildError(f"{sh.rel_posix(source.root, path)}: name={name!r} не совпадает с каталогом")
        if not body.strip():
            raise BuildError(f"{sh.rel_posix(source.root, path)}: пустое тело навыка")
        files[f"{name}/SKILL.md"] = skill_text(name, str(meta.get("description") or ""), body)
    return files


def build(root: Path, only: str | None = None) -> tuple[Source, dict[str, str], list[str]]:
    source = Source(root)
    domains = source.active_domains()
    if only:
        if only not in domains:
            raise BuildError(f"домен {only!r} не активен в манифесте")
        domains = [only]
    files: dict[str, str] = {}
    for domain in domains:
        files.update(domain_files(source, domain))
        files.update(procedure_files(source, domain))
    if not only:
        files.update(router_files(source, domains))
    for rel, text in authored_files(source).items():
        if rel in files:
            raise BuildError(f"навык {rel} объявлен дважды: авторский источник и проекция домена")
        files[rel] = text
    warnings = [f"{rel}: {text.count(chr(10))} строк — стандарт рекомендует до {MAX_BODY_LINES}"
                for rel, text in files.items() if text.count("\n") > MAX_BODY_LINES]
    return source, files, warnings


def stale_skills(out_dir: Path, files: dict[str, str]) -> list[Path]:
    if not out_dir.exists():
        return []
    known = {Path(rel).parts[0] for rel in files}
    stale: list[Path] = []
    for directory in sorted(out_dir.iterdir()):
        if not directory.is_dir() or directory.name in known:
            continue
        skill = directory / "SKILL.md"
        if skill.exists() and MARKER in skill.read_text(encoding="utf-8"):
            stale.append(directory)
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description="Сборка навыков Agent Skills")
    parser.add_argument("--root", default=str(sh.DEFAULT_ROOT))
    parser.add_argument("--check", action="store_true", help="только проверить дрейф (по умолчанию)")
    parser.add_argument("--write", action="store_true", help="записать результат")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--domain", default=None, help="только указанный активный домен")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    try:
        source, files, warnings = build(root, args.domain)
    except BuildError as error:
        print(str(error), file=sys.stderr)
        return 2

    stale = stale_skills(source.out_dir, files)

    if args.write:
        for directory in stale:
            shutil.rmtree(directory)
        for rel, text in files.items():
            target = source.out_dir / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        if not args.json:
            skills = len({Path(rel).parts[0] for rel in files})
            print(f"навыков: {skills}; файлов: {len(files)}; удалено устаревших: {len(stale)}; "
                  f"каталог: {sh.rel_posix(root, source.out_dir)}")
            for warning in warnings:
                print(f"  {warning}")
        return 0

    drift: list[str] = []
    for rel, text in files.items():
        target = source.out_dir / rel
        if not target.exists():
            drift.append(f"{rel}: не собран")
        elif target.read_text(encoding="utf-8") != text:
            drift.append(f"{rel}: расходится со сборкой")
    drift += [f"{sh.rel_posix(root, directory)}: устаревший навык" for directory in stale]

    if args.json:
        print(json.dumps({"skills": len({Path(rel).parts[0] for rel in files}),
                          "drift": drift, "warnings": warnings,
                          "ok": not drift}, ensure_ascii=False, indent=2))
        return 1 if drift else 0

    for item in drift + warnings:
        print(f"  {item}")
    if drift:
        print("\nнавыки: дрейф сборки — запустите `build_skills.py --write`")
        return 1
    print(f"навыки: актуальны ({len({Path(rel).parts[0] for rel in files})})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
